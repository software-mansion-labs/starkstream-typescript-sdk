import fsp from "node:fs/promises";
import { dirname, join, resolve } from "pathe";
import type { Starkstream } from "starkstream/types";
import { type JSValue, generateTypes, resolveSchema } from "untyped";
import { prettyPath } from "../path";

export async function writeTypes(starkstream: Starkstream) {
  // Check if the config file has a TypeScript extension so we assume it's a TypeScript project
  const isTypeScript = starkstream.options._c12.configFile?.endsWith(".ts");

  if (!isTypeScript) {
    // If it's not a TypeScript project, we don't need to generate the types
    return;
  }

  const typesDir = resolve(starkstream.options.buildDir, "types");

  const config = [
    "// Generated by starkstream",
    `
declare module "starkstream/types" {`,
    starkstream.options.typescript.generateRuntimeConfigTypes
      ? generateTypes(
          await resolveSchema(
            Object.fromEntries(
              Object.entries(starkstream.options.runtimeConfig),
            ) as Record<string, JSValue>,
          ),
          {
            interfaceName: "StarkstreamRuntimeConfig",
            addExport: false,
            addDefaults: false,
            allowExtraKeys: false,
            indentation: 2,
          },
        )
      : "",
    "}",
    // Makes this a module for augmentation purposes
    "export type {};",
  ];

  const buildFiles: { path: string; contents: string }[] = [];

  buildFiles.push({
    path: join(typesDir, "starkstream-config.d.ts"),
    contents: config.join("\n"),
  });

  await Promise.all(
    buildFiles.map(async (file) => {
      const _file = resolve(starkstream.options.buildDir, file.path);
      await fsp.mkdir(dirname(_file), { recursive: true });
      await fsp.writeFile(_file, file.contents);
    }),
  );

  if (!starkstream.options.disableLogs) {
    starkstream.logger.success(`Types written to ${prettyPath(typesDir)}`);
  }
}
